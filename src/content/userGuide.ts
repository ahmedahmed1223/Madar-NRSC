// --- Builders: keep the content below readable ------------------------------------------------

const p = (text: string): GuideBlock => ({ kind: 'p', text });
const steps = (...items: string[]): GuideBlock => ({ kind: 'steps', items });
const list = (...items: string[]): GuideBlock => ({ kind: 'list', items });
const sub = (text: string): GuideBlock => ({ kind: 'sub', text });
const tip = (text: string): GuideBlock => ({ kind: 'tip', text });
const warn = (text: string): GuideBlock => ({ kind: 'warning', text });
const screen = (id: string, label?: string): GuideBlock => ({ kind: 'screen', screen: id, ...(label ? { label } : {}) });
const screens = (...items: [string, string][]): GuideBlock => ({ kind: 'screens', items: items.map(([s, text]) => ({ screen: s, text })) });
const tour = (id: string): GuideBlock => ({ kind: 'tour', tour: id });
const see = (...entries: string[]): GuideBlock => ({ kind: 'see', entries });
const entry = (id: string, title: string, roles: UserRole[], screenIds: string[], body: GuideBlock[], keywords?: string): GuideEntry => ({ id, title, roles, screens: screenIds, body, ...(keywords ? { keywords } : {}) });

