/**
 * «دليل الاستخدام»: the long-form user guide of «مدار», as structured content.
 *
 * One source for the in-app guide (src/views/GuideView.tsx) and for docs/USER_GUIDE.md
 * (scripts/export-user-guide.mjs). Button and screen names are written exactly as they appear on
 * screen; when a screen changes its wording, change it here too (tests/content/userGuide.test.ts
 * checks that every screen, tour and cross-reference still exists).
 *
 * Six parts: «ابدأ هنا», a chapter per role family, a chapter per group of screens, step-by-step
 * how-tos, the glossary, and questions and troubleshooting.
 */
import type { UserRole } from '../types';

export type GuideBlock =
  | { kind: 'p'; text: string }
  /** Numbered steps, done in order. */
  | { kind: 'steps'; items: string[] }
  /** Unordered points. */
  | { kind: 'list'; items: string[] }
  /** A short heading inside an entry. */
  | { kind: 'sub'; text: string }
  | { kind: 'tip'; text: string }
  | { kind: 'warning'; text: string }
  /** «افتح الشاشة»: opens a screen through navigateTo (shown only to colleagues who may open it). */
  | { kind: 'screen'; screen: string; path?: string; label?: string }
  /** Screens with one line each; each gets its own «افتح» button. */
  | { kind: 'screens'; items: { screen: string; text: string }[] }
  /** «جرّب الجولة»: starts an interactive tour (src/content/tours.ts). */
  | { kind: 'tour'; tour: string }
  /** «اقرأ أيضاً»: another entry of this guide. */
  | { kind: 'see'; entries: string[] }
  /** Opens the administrator's quick-setup wizard (system.settings only). */
  | { kind: 'setup' };

export interface GuideEntry {
  id: string;
  title: string;
  /** Roles this entry is written for; empty means everyone. */
  roles: UserRole[];
  /** Screens the entry is about. */
  screens: string[];
  /** Extra words people may search with. */
  keywords?: string;
  body: GuideBlock[];
}

export type GuidePartId = 'start' | 'roles' | 'screens' | 'howto' | 'glossary' | 'faq';

export interface GuidePart {
  id: GuidePartId;
  title: string;
}

export interface GuideChapter {
  id: string;
  part: GuidePartId;
  title: string;
  /** One or two sentences under the chapter title. */
  intro: string;
  /** Role chapters: the roles of the family. */
  roles?: UserRole[];
  entries: GuideEntry[];
}

