// Generates src/styles/theme-dark.css from Tailwind's palette.
// Night mode remaps the colour variables every utility reads, so components need no `dark:` classes:
// accent scales are mirrored (50<->950, 100<->900, ...), neutral greys use tuned surface/text steps.
// The brand palette (scripts/palette.mjs) replaces the «slate» and «blue» scales in both modes,
// and the day values are written to src/styles/theme-light.css as Tailwind theme tokens.
// Run: node scripts/generate-dark-theme.mjs
import fs from 'fs';
import { INK, INK_NIGHT, SIGNAL, SURFACE_NIGHT } from './palette.mjs';

const theme = fs.readFileSync(new URL('../node_modules/tailwindcss/theme.css', import.meta.url), 'utf8');
const palette = {};
for (const m of theme.matchAll(/--color-([a-z]+)-(\d+):\s*([^;]+);/g)) {
  (palette[m[1]] ||= {})[m[2]] = m[3].trim();
}
palette.slate = { ...INK };
palette.blue = { ...SIGNAL };
const SHADES = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'];
const NEUTRALS = ['slate', 'gray', 'zinc', 'neutral', 'stone'];

const NEUTRAL_DARK = INK_NIGHT;
const WHITE_DARK = SURFACE_NIGHT; // cards & surfaces (and text on accent buttons)

const dark = [`  --color-white: ${WHITE_DARK};`];
const light = ['  --color-white: #fff;'];
for (const [name, scale] of Object.entries(palette)) {
  if (!SHADES.every((s) => scale[s])) continue;
  for (const s of SHADES) {
    light.push(`  --color-${name}-${s}: ${scale[s]};`);
    const mirrored = s === '50' ? '950' : s === '950' ? '50' : String(1000 - Number(s));
    let value = NEUTRALS.includes(name) ? NEUTRAL_DARK[s] : scale[mirrored];
    // Tinted panels (bg-*-50) blend into the card surface instead of glowing.
    if (!NEUTRALS.includes(name) && s === '50') value = `color-mix(in oklch, ${scale['950']} 55%, ${WHITE_DARK})`;
    dark.push(`  --color-${name}-${s}: ${value};`);
  }
}

// Solid accent fills (buttons, count badges) keep a strong day colour with white text at night;
// mirrored, they would turn pastel with dark text.
const SOLID = ['500', '600', '700', '800'];
const accents = Object.keys(palette).filter((n) => !NEUTRALS.includes(n) && SHADES.every((s) => palette[n][s]) && !['mauve', 'olive', 'mist', 'taupe'].includes(n));
const solid = accents.flatMap((name) => SOLID.map((sh) => `bg-${name}-${sh}`));
// The element and everything inside it (icons, hints, small badges) use the day palette.
const solidSelector = solid.map((c) => `.${c}`).join(', ');
const solidHoverSelector = solid.map((c) => `.hover\\:${c}:hover:not(:disabled)`).join(', ');
const solidRules = [
  `:root.dark :is(${solidSelector}):not(.theme-fixed, .theme-fixed *),`,
  `:root.dark :is(${solidHoverSelector}):not(.theme-fixed, .theme-fixed *) {`,
  ...light.map((l) => `  ${l.trim()}`),
  `}`,
];
const css = `/* Generated by scripts/generate-dark-theme.mjs — do not edit by hand. */

/* Night mode: remap the palette that every Tailwind utility reads. */
:root.dark {
  color-scheme: dark;
${dark.join('\n')}
}

/* Areas that are dark by design (sidebar, on-air widgets) keep their day palette. */
:root.dark .theme-fixed {
  color-scheme: dark;
${light.join('\n')}
}

${solidRules.join('\n')}
/* Printed reports always use the day palette. */
@media print {
  :root.dark {
    color-scheme: light;
${light.map((l) => `  ${l}`).join('\n')}
  }
}
`;
fs.writeFileSync(new URL('../src/styles/theme-dark.css', import.meta.url), css);

// Day values of the brand scales, read by every Tailwind utility.
const brand = (name, scale) => SHADES.map((s) => `  --color-${name}-${s}: ${scale[s]};`).join('\n');
fs.writeFileSync(
  new URL('../src/styles/theme-light.css', import.meta.url),
  `/* Generated by scripts/generate-dark-theme.mjs from scripts/palette.mjs — do not edit by hand. */\n@theme {\n${brand('slate', INK)}\n${brand('blue', SIGNAL)}\n}\n`
);
console.log(`wrote theme-dark.css (${Object.keys(palette).length} palettes)`);
