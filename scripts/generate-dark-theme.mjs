// Generates src/styles/theme-dark.css from Tailwind's palette.
// Night mode remaps the colour variables every utility reads, so components need no `dark:` classes:
// accent scales are mirrored (50<->950, 100<->900, ...), neutral greys use tuned surface/text steps.
// Run: node scripts/generate-dark-theme.mjs
import fs from 'fs';

const theme = fs.readFileSync(new URL('../node_modules/tailwindcss/theme.css', import.meta.url), 'utf8');
const palette = {};
for (const m of theme.matchAll(/--color-([a-z]+)-(\d+):\s*([^;]+);/g)) {
  (palette[m[1]] ||= {})[m[2]] = m[3].trim();
}
const SHADES = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'];
const NEUTRALS = ['slate', 'gray', 'zinc', 'neutral', 'stone'];

// Page, cards, panels, borders and text for night mode (slate hue).
const NEUTRAL_DARK = {
  50: 'oklch(17% 0.028 264)',
  100: 'oklch(25% 0.032 262)',
  200: 'oklch(31% 0.034 260)',
  300: 'oklch(40% 0.038 258)',
  400: 'oklch(56% 0.04 257)',
  500: 'oklch(66% 0.035 257)',
  600: 'oklch(76% 0.028 256)',
  700: 'oklch(85% 0.018 255)',
  800: 'oklch(91% 0.012 255)',
  900: 'oklch(95% 0.007 250)',
  950: 'oklch(98% 0.003 248)',
};
const WHITE_DARK = 'oklch(21.5% 0.032 264)'; // cards & surfaces (and text on accent buttons)

const dark = [`  --color-white: ${WHITE_DARK};`];
const light = ['  --color-white: #fff;'];
for (const [name, scale] of Object.entries(palette)) {
  if (!SHADES.every((s) => scale[s])) continue;
  for (const s of SHADES) {
    light.push(`  --color-${name}-${s}: ${scale[s]};`);
    const mirrored = s === '50' ? '950' : s === '950' ? '50' : String(1000 - Number(s));
    dark.push(`  --color-${name}-${s}: ${NEUTRALS.includes(name) ? NEUTRAL_DARK[s] : scale[mirrored]};`);
  }
}

const css = `/* Generated by scripts/generate-dark-theme.mjs — do not edit by hand. */

/* Night mode: remap the palette that every Tailwind utility reads. */
:root.dark {
  color-scheme: dark;
${dark.join('\n')}
}

/* Areas that are dark by design (sidebar, on-air widgets) keep their day palette. */
:root.dark .theme-fixed {
  color-scheme: dark;
${light.join('\n')}
}

/* Printed reports always use the day palette. */
@media print {
  :root.dark {
    color-scheme: light;
${light.map((l) => `  ${l}`).join('\n')}
  }
}
`;
fs.writeFileSync(new URL('../src/styles/theme-dark.css', import.meta.url), css);
console.log(`wrote theme-dark.css (${Object.keys(palette).length} palettes)`);
