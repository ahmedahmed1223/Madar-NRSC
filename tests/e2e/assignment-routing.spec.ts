import { expect, test } from '@playwright/test';
import { openNav, signIn } from './helpers';

test('a manager keeps explicit template choices and can find a saved assignment that still needs staffing', async ({ browser }) => {
  const session = await signIn(browser, 'editor@akhbar.tv');
  const { page } = session;
  await openNav(page, 'التكليفات');
  await page.getByRole('button', { name: 'تكليف من قالب', exact: true }).click();
  await page.locator('#asg-template').selectOption('wft-bulletin');
  const station = page.locator('#asg-station');
  await station.selectOption({ index: 1 });
  const stationId = await station.inputValue();
  await page.locator('#asg-pick-b1').selectOption(`s:${stationId}`);
  await page.locator('#asg-pick-b2').selectOption('');
  await page.getByLabel('تكليف عاجل').check();
  await station.selectOption({ index: 2 });
  await expect(page.getByLabel('تكليف عاجل')).toBeChecked();
  await expect(page.locator('#asg-pick-b1')).toHaveValue(`s:${stationId}`);
  await expect(page.locator('#asg-pick-b2')).toHaveValue('');
  const title = 'متابعة إسناد طاقم النشرة';
  await page.locator('#asg-title').fill(title);
  await page.getByRole('button', { name: 'إنشاء التكليف', exact: true }).click();
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible();
  const id = new URL(page.url()).pathname.split('/').pop();
  const data = await (await page.request.get('/api/v1/data')).json();
  const saved = data.collections.productionCards.find((row: { id: string }) => row.id === id).d;
  expect(saved.priority).toBe('URGENT');
  expect(saved.steps[0].stationId).toBe(stationId);
  expect([saved.steps[1].assigneeId, saved.steps[1].stationId, saved.steps[1].departmentId]).toEqual([undefined, undefined, undefined]);
  await page.goto('/cards');
  await page.getByRole('tab', { name: /كل التكليفات/ }).click();
  await page.getByLabel('فيها مهام بلا إسناد').check();
  await expect(page.getByRole('button', { name: new RegExp(title) }).first()).toBeVisible();
  await page.getByRole('button', { name: 'تكليف حر', exact: true }).click();
  const pooled = 'تسليم نسخة النشرة إلى غرفة التحرير';
  await page.getByLabel('عنوان المادة *').fill(pooled);
  const removeStep = page.getByRole('button', { name: 'حذف المهمة' });
  while (await removeStep.count() > 1) await removeStep.last().click();
  const recipient = page.getByLabel('المكلف', { exact: true });
  const poolTarget = `d:newsroom:${stationId}`;
  await recipient.selectOption(poolTarget);
  await page.getByRole('button', { name: 'إنشاء التكليف', exact: true }).click();
  await expect(page.getByRole('button', { name: new RegExp(pooled) })).toHaveCount(0);
  await page.getByRole('button', { name: 'فتح التكليف', exact: true }).click();
  await expect(page.getByRole('heading', { name: pooled })).toBeVisible();
  await page.getByRole('button', { name: 'تعديل التكليف والمهام' }).click();
  await expect(recipient).toHaveValue(poolTarget);
  await recipient.selectOption('');
  await page.getByRole('button', { name: 'حفظ التكليف', exact: true }).click();
  await expect(page.getByText('حُفظ التكليف', { exact: true })).toBeVisible();
  await page.goto('/cards');
  await expect(page.getByRole('button', { name: new RegExp(pooled) })).toBeVisible();
  expect(session.errors).toEqual([]);
  await session.close();
});
